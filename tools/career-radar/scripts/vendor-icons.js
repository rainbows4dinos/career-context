import { createRequire } from 'node:module';
import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { createHash } from 'node:crypto';

const require = createRequire(import.meta.url);
const appRoot = new URL('../', import.meta.url);
const outputRoot = new URL('../../shared/vendor/gravity-icons/', import.meta.url);
const readJson = async path => JSON.parse(await readFile(path, 'utf8'));
const app = await readJson(new URL('package.json', appRoot));
const lock = await readJson(new URL('package-lock.json', appRoot));
const packageRoot = dirname(require.resolve('@gravity-ui/icons/package.json'));
const pkg = await readJson(join(packageRoot, 'package.json'));
const locked = lock.packages['node_modules/@gravity-ui/icons'];
if (pkg.version !== app.devDependencies['@gravity-ui/icons'] || locked.version !== pkg.version) {
  throw new Error('Installed icons must match the exact package and lockfile version. Run npm ci.');
}
const names = [];
const symbols = [];
for (const file of (await readdir(join(packageRoot, 'svgs'))).filter(name => name.endsWith('.svg')).sort()) {
  const name = file.slice(0, -4);
  const source = await readFile(join(packageRoot, 'svgs', file), 'utf8');
  const match = /^<svg\s+([^>]+)>([\s\S]*)<\/svg>\s*$/.exec(source);
  if (!/^[a-z0-9-]+$/.test(name) || !match || !/viewBox="0 0 (16 16|17 17)"/.test(source)) {
    throw new Error(`Upstream SVG shape changed: ${file}`);
  }
  // Internal clipPath IDs repeat across upstream files; namespace their references.
  let body = match[2];
  const ids = [...body.matchAll(/\bid="([^"]+)"/g)].map(item => item[1]);
  for (const id of ids) {
    body = body.replaceAll(`id="${id}"`, `id="${name}--${id}"`)
      .replaceAll(`url(#${id})`, `url(#${name}--${id})`)
      .replaceAll(`href="#${id}"`, `href="#${name}--${id}"`);
  }
  const attrs = match[1].replace(/\s*(?:xmlns|width|height)="[^"]*"/g, '').trim();
  symbols.push(`<symbol id="${name}" ${attrs}>${body}</symbol>`);
  names.push(name);
}
const sprite = '<svg xmlns="http://www.w3.org/2000/svg">\n' + symbols.join('\n') + '\n</svg>\n';
const outputs = {
  'sprite.svg': sprite,
  'names.mjs': '// Generated by Radar scripts/vendor-icons.js.\nexport const gravityIconNames = Object.freeze(' + JSON.stringify(names) + ');\n',
  'LICENSE': await readFile(join(packageRoot, 'LICENSE'), 'utf8'),
  'provenance.json': JSON.stringify({ package: pkg.name, version: pkg.version, upstreamDirectory: 'svgs/',
    npmIntegrity: locked.integrity, iconCount: names.length,
    spriteSha256: createHash('sha256').update(sprite).digest('hex') }, null, 2) + '\n'
};
if (process.argv.includes('--check')) {
  for (const [file, content] of Object.entries(outputs)) {
    if (await readFile(new URL(file, outputRoot), 'utf8') !== content) throw new Error(`Vendored ${file} differs. Run npm run icons:generate.`);
  }
  console.log(`Gravity UI ${pkg.version}: ${names.length} icons, license and provenance verified.`);
} else {
  await mkdir(outputRoot, { recursive: true });
  for (const [file, content] of Object.entries(outputs)) await writeFile(new URL(file, outputRoot), content);
  console.log(`Vendored ${names.length} Gravity UI ${pkg.version} icons.`);
}
