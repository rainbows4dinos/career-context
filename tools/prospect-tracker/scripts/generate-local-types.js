import { writeFile } from 'node:fs/promises';
import { createLocalDatabase } from './local-database.js';

// Bootstrap snapshot from PostgreSQL introspection, not handwritten types.
// Replace via `npm run types:generate` after applying to hosted Supabase.
const db = await createLocalDatabase();
try {
  const { rows } = await db.query(`
    select table_name, column_name, udt_name, is_nullable, column_default, is_identity
    from information_schema.columns
    where table_schema = 'public'
      and table_name in ('prospects', 'prospect_status_events', 'career_profiles', 'radar_opportunities')
    order by table_name, ordinal_position;
  `);
  const typeMap = { uuid: 'string', text: 'string', date: 'string', timestamptz: 'string', int2: 'number', int8: 'number', jsonb: 'Json' };
  let output = '// Generated by scripts/generate-local-types.js from the migration applied to PGlite PostgreSQL.\n';
  output += '// Bootstrap snapshot; regenerate from Supabase with npm run types:generate after migration.\n';
  output += 'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\n';
  output += 'export type Database = {\n  public: {\n    Tables: {\n';
  for (const table of ['prospects', 'prospect_status_events', 'career_profiles', 'radar_opportunities']) {
    const columns = rows.filter(row => row.table_name === table);
    if (!columns.length) throw new Error(`Missing table: ${table}`);
    output += `      ${table}: {\n`;
    for (const operation of ['Row', 'Insert', 'Update']) {
      output += `        ${operation}: {\n`;
      for (const column of columns) {
        const type = typeMap[column.udt_name];
        if (!type) throw new Error(`Unsupported database type: ${column.udt_name}`);
        const generated = column.is_identity === 'YES';
        const optional = operation === 'Update' || (operation === 'Insert' && (column.is_nullable === 'YES' || column.column_default !== null || generated));
        const valueType = operation !== 'Row' && generated ? 'never' : type + (column.is_nullable === 'YES' ? ' | null' : '');
        output += `          ${column.column_name}${optional ? '?' : ''}: ${valueType};\n`;
      }
      output += '        };\n';
    }
    output += table === 'prospect_status_events'
      ? '        Relationships: [{ foreignKeyName: "prospect_status_events_prospect_id_fkey"; columns: ["prospect_id"]; isOneToOne: false; referencedRelation: "prospects"; referencedColumns: ["id"]; }];\n'
      : '        Relationships: [];\n';
    output += '      };\n';
  }
  const { rows: functions } = await db.query(`select p.proname, pg_get_function_arguments(p.oid) as args from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = 'reorder_prospect_column'`);
  if (functions.length !== 1 || functions[0].args !== 'column_id text, expected_ids uuid[], ordered_ids uuid[]') throw new Error('Unexpected reorder RPC signature');
  output += '    };\n    Views: { [_ in never]: never };\n    Functions: { reorder_prospect_column: { Args: { column_id: string; expected_ids: string[]; ordered_ids: string[] }; Returns: undefined } };\n    Enums: { [_ in never]: never };\n    CompositeTypes: { [_ in never]: never };\n  };\n};\n';
  await writeFile(new URL('../database.types.ts', import.meta.url), output);
  console.log('Generated migration-based PostgreSQL schema snapshot. Hosted Supabase generation is still required after deployment.');
} finally {
  await db.close();
}
